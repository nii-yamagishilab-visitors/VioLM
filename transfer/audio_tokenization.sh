#!/bin/bash

set -eou pipefail

# fix segmentation fault reported in https://github.com/k2-fsa/icefall/issues/674
export PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION=python

nj=8
stage=2
stop_stage=3


dataset_parts="--dataset-parts all"  # all

folder_name=local/MUSC
audio_extractor="Encodec32FT"  # or Fbank
audio_feats_dir=${folder_name}/tokenized_articulation

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT_DIR}"

# Reuse MIDI-VALLE's egs/atepp tokenization utilities (bin/*, shared/*)
# since this repo doesn't vendor them.
TOKENIZER_PY="model/tokenizer.py"
STATS_PY="model/display_manifest_statistics.py"


# All files generated by this script are saved in "data".
# You can safely remove "data" and rerun this script to regenerate it.
# mkdir -p data

log() {
  # This function is from espnet
  local fname=${BASH_SOURCE[1]##*/}
  echo -e "$(date '+%Y-%m-%d %H:%M:%S') (${fname}:${BASH_LINENO[0]}:${FUNCNAME[1]}) $*"
}

if [ $stage -le 2 ] && [ $stop_stage -ge 2 ]; then
  log "Stage 2: Tokenize/Fbank ATEPP"
  mkdir -p ${audio_feats_dir}
  if [ ! -e ${audio_feats_dir}/.tokenize.done ]; then
    python3 "${TOKENIZER_PY}" --dataset-parts "${dataset_parts}" \
        --audio-extractor ${audio_extractor} \
        --batch-duration 150 \
        --src-dir "${folder_name}/manifests_articulation" \
        --output-dir "${audio_feats_dir}" \
        --prefix ""
  fi
  touch ${audio_feats_dir}/.tokenize.done
fi


python3 "${STATS_PY}" --manifest-dir ${audio_feats_dir}
